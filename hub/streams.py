"""The hub's own go2rtc: generated from the camera list and run as a child process, so a hub is one
container with nothing else to configure.

Each camera with a `url` gets these restreams:
    <id>        the camera's main stream, untouched (desktop/projector popups, recording)
    <id>_sd     its sub stream, when it has one (detection reads it; otherwise the main stream,
                which the detector shrinks itself - cheaper than re-encoding a copy)
    <id>_watch  480 px H.264 with a keyframe every ~0.5 s, made only while someone watches (HLS)
    <id>_phone  640-960 px version of the same for the iPhone

Cameras configured the old way (`detect_url` pointing at an external go2rtc) are passed through.
"""

import logging
import os
import shutil
import socket
import subprocess
import threading
import time
from pathlib import Path

log = logging.getLogger("lookout-hub")

_ENCODE = ("-an -c:v libx264 -preset superfast -tune zerolatency -profile:v main -pix_fmt yuv420p "
           "-r 15 -g 7 -keyint_min 7 -sc_threshold 0")


def lan_ip():
    """This machine's address on the LAN (no packets are sent)."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("10.255.255.255", 1))
            return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"


def resolve(cam, rtsp_port, public_host):
    """A stored camera -> what the detector and clients use (detect_url, streams, hls names)."""
    cam = dict(cam)
    if cam.get("url") and not cam.get("detect_url"):
        cid = cam["id"]
        sd = f"{cid}_sd" if cam.get("sub_url") else cid
        cam["detect_url"] = f"rtsp://127.0.0.1:{rtsp_port}/{sd}"
        cam["streams"] = {"hd": f"rtsp://{public_host}:{rtsp_port}/{cid}",
                          "sd": f"rtsp://{public_host}:{rtsp_port}/{sd}"}
        cam.setdefault("hls_src", f"{cid}_watch")
        cam.setdefault("hls_variants", {"phone": f"{cid}_phone"})
    return cam


def go2rtc_yaml(cameras, api_port, rtsp_port):
    """go2rtc config for the cameras that have a `url`."""
    local = f"rtsp://127.0.0.1:{rtsp_port}"
    lines = ["# Generated by Lookout Hub from its camera list - edits are overwritten.",
             "api:", f'  listen: "127.0.0.1:{api_port}"', "rtsp:", f'  listen: ":{rtsp_port}"',
             "webrtc:", '  listen: ""', "srtp:", '  listen: ""', "log:", "  level: warn", "streams:"]
    for cam in cameras:
        if not cam.get("url") or cam.get("detect_url"):
            continue
        cid = cam["id"]
        lines.append(f"  {cid}: {_quote(cam['url'])}")
        if cam.get("sub_url"):
            lines.append(f"  {cid}_sd: {_quote(cam['sub_url'])}")
        src = f"{local}/{cid}_sd" if cam.get("sub_url") else f"{local}/{cid}"
        lines.append(f"  {cid}_watch: {_quote(f'exec:ffmpeg -hide_banner -loglevel error -rtsp_transport tcp -i {src} -vf scale=480:-2 {_ENCODE} -b:v 350k -maxrate 450k -bufsize 300k -f rtsp {{output}}')}")
        lines.append(f"  {cid}_phone: {_quote(f'exec:ffmpeg -hide_banner -loglevel error -rtsp_transport tcp -i {local}/{cid} -vf scale=960:-2 {_ENCODE} -b:v 900k -maxrate 1200k -bufsize 600k -f rtsp {{output}}')}")
    return "\n".join(lines) + "\n"


def _quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


class Go2rtc:
    """Runs go2rtc with a generated config; restarted when the cameras change or it dies."""

    def __init__(self, data_dir, api_port, rtsp_port, binary=None):
        self.config = Path(data_dir) / "go2rtc.yaml"
        self.api_port = api_port
        self.rtsp_port = rtsp_port
        self.binary = binary or shutil.which("go2rtc")
        self.proc = None
        self.lock = threading.Lock()
        self._stop = threading.Event()
        self._text = None

    @property
    def available(self):
        return bool(self.binary)

    def apply(self, cameras):
        """Write the config for these cameras and (re)start go2rtc if it changed."""
        text = go2rtc_yaml(cameras, self.api_port, self.rtsp_port)
        with self.lock:
            if text == self._text and self.proc and self.proc.poll() is None:
                return False
            self.config.parent.mkdir(parents=True, exist_ok=True)
            self.config.write_text(text, encoding="utf-8")
            os.chmod(self.config, 0o600)   # has camera passwords in it
            self._text = text
            self._restart()
            return True

    def _restart(self):
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(5)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = subprocess.Popen([self.binary, "-config", str(self.config)],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        log.info("go2rtc started (pid %d, rtsp :%d, api :%d)", self.proc.pid, self.rtsp_port, self.api_port)

    def watchdog(self):
        """Background thread: bring go2rtc back if it exits."""
        def run():
            while not self._stop.wait(5):
                with self.lock:
                    if self._text is not None and self.proc and self.proc.poll() is not None:
                        log.warning("go2rtc exited (%s), restarting", self.proc.returncode)
                        time.sleep(1)
                        self._restart()
        threading.Thread(target=run, name="go2rtc-watchdog", daemon=True).start()

    def stop(self):
        self._stop.set()
        with self.lock:
            if self.proc and self.proc.poll() is None:
                self.proc.terminate()
