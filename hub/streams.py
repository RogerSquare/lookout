"""The hub's own go2rtc: generated from the camera list and run as a child process, so a hub is one
container with nothing else to configure.

Each camera with a `url` gets these restreams:
    <id>        the camera's main stream, untouched (desktop/projector popups, recording)
    <id>_sd     its sub stream, when it has one (detection reads it; otherwise the main stream,
                which the detector shrinks itself - cheaper than re-encoding a copy)
    <id>_watch  480 px H.264 with a keyframe every ~0.5 s, made only while someone watches (HLS)
    <id>_phone  640-960 px version of the same for the iPhone

HLS variants an app can pick (stream.m3u8?v=<name>): "phone" (<id>_phone) and "hd" (<id>, the
camera's own full-resolution stream with its sound, copied rather than re-encoded; the iPhone's
full-screen player).

Cameras configured the old way (`detect_url` pointing at an external go2rtc) are passed through.
"""

import logging
import os
import shutil
import socket
import subprocess
import threading
import time
from pathlib import Path

log = logging.getLogger("lookout-hub")

_ENCODE = ("-an -c:v libx264 -preset superfast -tune zerolatency -profile:v main -pix_fmt yuv420p "
           "-r 15 -g 7 -keyint_min 7 -sc_threshold 0")


def lan_ip():
    """This machine's address on the LAN (no packets are sent)."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("10.255.255.255", 1))
            return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"


def resolve(cam, rtsp_port, public_host):
    """A stored camera -> what the detector and clients use (detect_url, streams, hls names)."""
    cam = dict(cam)
    if cam.get("url") and not cam.get("detect_url"):
        cid = cam["id"]
        sd = f"{cid}_sd" if cam.get("sub_url") else cid
        cam["detect_url"] = f"rtsp://127.0.0.1:{rtsp_port}/{sd}"
        cam["streams"] = {"hd": f"rtsp://{public_host}:{rtsp_port}/{cid}",
                          "sd": f"rtsp://{public_host}:{rtsp_port}/{sd}"}
        cam.setdefault("hls_src", f"{cid}_watch")
        # Stored variants win; the defaults fill in the rest (cameras saved before "hd" existed get it)
        cam["hls_variants"] = {"phone": f"{cid}_phone", "hd": cid, **(cam.get("hls_variants") or {})}
    return cam


def go2rtc_yaml(cameras, api_port, rtsp_port):
    """go2rtc config for the cameras that have a `url`."""
    local = f"rtsp://127.0.0.1:{rtsp_port}"
    lines = ["# Generated by Lookout Hub from its camera list - edits are overwritten.",
             "api:", f'  listen: "127.0.0.1:{api_port}"', "rtsp:", f'  listen: ":{rtsp_port}"',
             "webrtc:", '  listen: ""', "srtp:", '  listen: ""', "log:", "  level: warn", "streams:"]
    for cam in cameras:
        if not cam.get("url") or cam.get("detect_url"):
            continue
        cid = cam["id"]
        lines.append(f"  {cid}: {_quote(cam['url'])}")
        if cam.get("sub_url"):
            lines.append(f"  {cid}_sd: {_quote(cam['sub_url'])}")
        src = f"{local}/{cid}_sd" if cam.get("sub_url") else f"{local}/{cid}"
        lines.append(f"  {cid}_watch: {_quote(f'exec:ffmpeg -hide_banner -loglevel error -rtsp_transport tcp -i {src} -vf scale=480:-2 {_ENCODE} -b:v 350k -maxrate 450k -bufsize 300k -f rtsp {{output}}')}")
        lines.append(f"  {cid}_phone: {_quote(f'exec:ffmpeg -hide_banner -loglevel error -rtsp_transport tcp -i {local}/{cid} -vf scale=960:-2 {_ENCODE} -b:v 900k -maxrate 1200k -bufsize 600k -f rtsp {{output}}')}")
    return "\n".join(lines) + "\n"


def _quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


HEALTH_EVERY = 120       # seconds between restream checks
HEALTH_STRIKES = 2       # failed checks in a row before go2rtc is restarted
HEALTH_COOLDOWN = 900    # never restart go2rtc for health more often than this (seconds)


def restream_sources(config_text):
    """{name: source url} for the camera restreams in a go2rtc config (not the exec: variants)."""
    found, in_streams = {}, False
    for line in config_text.splitlines():
        if line.startswith("streams:"):
            in_streams = True
        elif in_streams and line.startswith("  ") and ":" in line:
            name, _, src = line.strip().partition(":")
            src = src.strip().strip('"')
            if not src.startswith("exec:"):
                found[name] = src
        elif in_streams and line and not line.startswith(" "):
            in_streams = False
    return found


def restreams(config_text):
    """Names of the camera restreams in a go2rtc config (not the exec: variants made from them)."""
    return list(restream_sources(config_text))


def has_video(url, timeout=15):
    """True if the stream gives a decodable picture size. A restream can go bad and keep
    sending video packets nobody can decode (lost parameter sets): players then freeze."""
    try:
        r = subprocess.run(["ffprobe", "-v", "error", "-rtsp_transport", "tcp", "-select_streams", "v:0",
                            "-show_entries", "stream=width", "-of", "csv=p=0", url],
                           capture_output=True, text=True, timeout=timeout)
    except (subprocess.TimeoutExpired, OSError):
        return False
    return r.stdout.strip().split(",")[0].isdigit() and int(r.stdout.strip().split(",")[0]) > 0


class Go2rtc:
    """Runs go2rtc with a generated config; restarted when the cameras change, when it dies, and
    when one of its camera restreams stops carrying a usable picture."""

    def __init__(self, data_dir, api_port, rtsp_port, binary=None):
        self.config = Path(data_dir) / "go2rtc.yaml"
        self.api_port = api_port
        self.rtsp_port = rtsp_port
        self.binary = binary or shutil.which("go2rtc")
        self.proc = None
        self.lock = threading.Lock()
        self._stop = threading.Event()
        self._text = None
        self.strikes = {}          # restream name -> failed checks in a row
        self.started_at = 0.0
        self.healed_at = 0.0       # last restart made by the health check

    @property
    def available(self):
        return bool(self.binary)

    def apply(self, cameras):
        """Write the config for these cameras and (re)start go2rtc if it changed."""
        text = go2rtc_yaml(cameras, self.api_port, self.rtsp_port)
        with self.lock:
            if text == self._text and self.proc and self.proc.poll() is None:
                return False
            self.config.parent.mkdir(parents=True, exist_ok=True)
            self.config.write_text(text, encoding="utf-8")
            os.chmod(self.config, 0o600)   # has camera passwords in it
            self._text = text
            self._restart()
            return True

    def _restart(self):
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(5)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = subprocess.Popen([self.binary, "-config", str(self.config)],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.started_at = time.time()
        self.strikes = {}
        log.info("go2rtc started (pid %d, rtsp :%d, api :%d)", self.proc.pid, self.rtsp_port, self.api_port)

    def watchdog(self):
        """Background threads: bring go2rtc back if it exits, and if a restream goes bad."""
        def run():
            while not self._stop.wait(5):
                with self.lock:
                    if self._text is not None and self.proc and self.proc.poll() is not None:
                        log.warning("go2rtc exited (%s), restarting", self.proc.returncode)
                        time.sleep(1)
                        self._restart()
        threading.Thread(target=run, name="go2rtc-watchdog", daemon=True).start()
        threading.Thread(target=self._health_loop, name="go2rtc-health", daemon=True).start()

    def live_producers(self):
        """Names of the restreams go2rtc is pulling from their camera right now (None if its API
        doesn't answer). Asking costs the camera nothing."""
        import json
        import urllib.request
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{self.api_port}/api/streams", timeout=5) as r:
                streams = json.load(r) or {}
        except Exception:
            return None
        return {name for name, st in streams.items()
                if any(p.get("remote_addr") or p.get("receivers") for p in (st or {}).get("producers") or [])}

    def check_health(self):
        """Restart go2rtc after HEALTH_STRIKES bad checks in a row on a restream that is pulling
        from its camera but gives no usable picture (the lost-parameter-sets failure).

        Passive towards the cameras: only restreams go2rtc is already pulling are probed (the probe
        joins that session), and a camera is never contacted directly. A camera that is offline,
        or that nobody is watching, is left alone: restarting go2rtc can't fix it, and extra
        connections are what wedges a fragile camera. Returns the names that failed this round."""
        text = self._text
        if not text or not self.proc or self.proc.poll() is not None or time.time() - self.started_at < 60:
            return []
        live = self.live_producers()
        if live is None:
            return []
        failed = []
        for name in restream_sources(text):
            if self._stop.is_set():
                return failed
            if name not in live:
                self.strikes[name] = 0
                continue
            if has_video(f"rtsp://127.0.0.1:{self.rtsp_port}/{name}"):
                self.strikes[name] = 0
                continue
            failed.append(name)
            self.strikes[name] = self.strikes.get(name, 0) + 1
        bad = [n for n, k in self.strikes.items() if k >= HEALTH_STRIKES]
        if bad and time.time() - self.healed_at >= HEALTH_COOLDOWN:
            log.warning("go2rtc: %s gave no usable picture %d checks in a row; restarting go2rtc",
                        ", ".join(bad), HEALTH_STRIKES)
            self.healed_at = time.time()
            with self.lock:
                if self._text is not None:
                    self._restart()
        return failed

    def _health_loop(self):
        while not self._stop.wait(HEALTH_EVERY):
            try:
                self.check_health()
            except Exception:
                log.exception("go2rtc health check failed")

    def stop(self):
        self._stop.set()
        with self.lock:
            if self.proc and self.proc.poll() is None:
                self.proc.terminate()
